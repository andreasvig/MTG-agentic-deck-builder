/**
 * Bring Scryfall's card symbols local.
 *
 * Rules text is dense with symbols — a single ability can carry five — so these are
 * served from our own origin rather than hotlinked, the same way the catalog and the
 * tagger data are synced once and then read offline. The set is small (~84 files,
 * ~360 KB) and changes about as often as Wizards prints a new symbol, so the output
 * is committed: a fresh clone renders symbols without running anything.
 *
 * Writes:
 *   frontend/public/card-symbols/*.svg
 *   frontend/src/domain/cardSymbols.generated.ts
 *
 * Run with `npm run symbols:sync`.
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const SYMBOLOGY_URL = "https://api.scryfall.com/symbology";
const USER_AGENT = "mtg-agentic-deck-builder/0.1";
const ASSET_DIR = path.join("frontend", "public", "card-symbols");
const MANIFEST = path.join("frontend", "src", "domain", "cardSymbols.generated.ts");

// Scryfall's own file names, which we keep, are all of this shape. Anything else
// would be a path we are about to write into a public directory from a remote body.
const SAFE_FILE = /^[A-Za-z0-9]+\.svg$/;

async function main() {
  const symbols = await fetchSymbology();
  console.log(`Fetched ${symbols.length} symbols from Scryfall.`);

  await mkdir(ASSET_DIR, { recursive: true });

  const written = new Set();
  for (const symbol of symbols) {
    const file = path.posix.basename(new URL(symbol.svg_uri).pathname);
    if (!SAFE_FILE.test(file)) {
      throw new Error(`Refusing to write unexpected file name ${file} for ${symbol.symbol}`);
    }
    if (!written.has(file)) {
      const svg = await fetchText(symbol.svg_uri);
      if (!svg.includes("<svg")) {
        throw new Error(`${symbol.svg_uri} did not return an SVG`);
      }
      await writeFile(path.join(ASSET_DIR, file), svg, "utf8");
      written.add(file);
    }
    symbol.file = file;
  }

  // Stale files go only after every new one is on disk, so an interrupted run
  // leaves the previous set intact rather than an empty directory.
  for (const existing of await readdir(ASSET_DIR)) {
    if (existing.endsWith(".svg") && !written.has(existing)) {
      await rm(path.join(ASSET_DIR, existing));
      console.log(`Removed retired symbol ${existing}.`);
    }
  }

  await writeFile(MANIFEST, renderManifest(symbols), "utf8");
  console.log(`Wrote ${written.size} SVGs to ${ASSET_DIR} and ${MANIFEST}.`);
}

async function fetchSymbology() {
  const payload = JSON.parse(await fetchText(SYMBOLOGY_URL));
  if (payload.has_more) {
    // The endpoint has never paginated. If it starts, a silent half-set would be
    // worse than a failed sync.
    throw new Error("Symbology is paginated now; this script only reads one page.");
  }
  const symbols = payload.data ?? [];
  if (symbols.length === 0) {
    throw new Error("Symbology returned no symbols.");
  }
  return symbols;
}

async function fetchText(url) {
  const response = await fetch(url, {
    headers: { "User-Agent": USER_AGENT, Accept: "*/*" },
  });
  if (!response.ok) {
    throw new Error(`${url} responded ${response.status}`);
  }
  return response.text();
}

function renderManifest(symbols) {
  const entries = symbols
    .map(
      (symbol) =>
        `  ${JSON.stringify(symbol.symbol)}: ` +
        `{ file: ${JSON.stringify(symbol.file)}, ` +
        `label: ${JSON.stringify(symbol.english)} },`,
    )
    .join("\n");

  return `// Generated by scripts/sync-card-symbols.mjs from ${SYMBOLOGY_URL}.
// Do not edit by hand — run \`npm run symbols:sync\`.
//
// Symbol artwork is Wizards of the Coast's, distributed by Scryfall; it is kept here
// so the interface renders rules text without reaching the network.

export interface CardSymbolAsset {
  /** File name inside \`public/card-symbols/\`. */
  readonly file: string;
  /** Scryfall's reading of the symbol, used as the image's alternative text. */
  readonly label: string;
}

/** Keyed by Scryfall's own braced notation, exactly as it appears in rules text. */
export const CARD_SYMBOLS: Readonly<Record<string, CardSymbolAsset>> = {
${entries}
};
`;
}

main().catch((error) => {
  console.error(error.message ?? error);
  process.exitCode = 1;
});
